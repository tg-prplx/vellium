import { describe, expect, it } from "vitest";
import { findQuotedLine, parseDirectorReply } from "./liteDirector.js";
import { liteAssistantText } from "./litePrompt.js";
import { previewText } from "./liteGeneration.js";

// All story text here is synthetic.
const scenes = [
  { lines: [{ speaker: "", text: "Fog drifts over the invented pier." }, { speaker: "Mira", text: "Did you bring the synthetic key?" }] },
  { lines: [{ speaker: "", text: "Shelves of invented ledgers fill the hall." }] }
];

describe("lite director", () => {
  it("finds a line from a copied prefix, in any case, or not at all", () => {
    expect(findQuotedLine(scenes, "Fog drifts over the")).toEqual({ scene: 0, line: 0 });
    expect(findQuotedLine(scenes, "did you BRING the synthetic")).toEqual({ scene: 0, line: 1 });
    expect(findQuotedLine(scenes, "Mira: Did you bring")).toEqual({ scene: 0, line: 1 });
    expect(findQuotedLine(scenes, "invented ledgers")).toEqual({ scene: 1, line: 0 });
    expect(findQuotedLine(scenes, "Shelves of invented books everywhere")).toEqual({ scene: 1, line: 0 });
    expect(findQuotedLine(scenes, "A sentence that is not there")).toBeNull();
    expect(findQuotedLine(scenes, "")).toBeNull();
  });
  it("reads JSON, truncated JSON, the line format and ignores noise", () => {
    expect(parseDirectorReply('{"question":"What now?","choices":["Go","Stay"],"people":[{"name":"Mira","look":"short silver hair","clothes":"raincoat"}],"places":[],"shots":[{"at":"Fog drifts","who":["Mira"],"camera":"sideways","see":"Wide view."}],"outfits":[]}'))
      .toMatchObject({ question: "What now?", choices: ["Go", "Stay"], people: [{ name: "Mira" }], shots: [{ at: "Fog drifts", who: ["Mira"], see: "Wide view." }] });
    expect(parseDirectorReply('{"shots":[{"at":"Fog drifts","who":"Mira and Ren","see":"Two figures."},{"at":"Shel').shots).toEqual([{ at: "Fog drifts", who: ["Mira", "Ren"], see: "Two figures." }]);
    const lines = parseDirectorReply("Here you go:\n1. PERSON | Ren | tall man, scar | grey coat\nSHOT | Fog drifts over | none | Empty pier.\nOUTFIT | Mira | swimsuit | Did you bring\n**ASK** | What do you do?\nOPTION | Go\nOPTION | Stay");
    expect(lines).toMatchObject({ people: [{ name: "Ren", look: "tall man, scar", clothes: "grey coat" }], shots: [{ at: "Fog drifts over", who: [], see: "Empty pier." }], outfits: [{ name: "Mira", at: "Did you bring" }], question: "What do you do?", choices: ["Go", "Stay"] });
    expect(parseDirectorReply("I cannot help with that.")).toEqual({ question: "", choices: [], people: [], places: [], shots: [], outfits: [] });
  });
  it("keeps the generated bytes when the reply is already canonical", () => {
    const canonical = [{ location: "Test pier", lines: scenes[0].lines }];
    const raw = "## Test pier\nFog drifts over the invented pier.\nMira: Did you bring the synthetic key?";
    expect(liteAssistantText(raw, canonical)).toBe(raw);
    expect(liteAssistantText(`\n${raw.replace(/\n/g, "\n\n")}  \n`, canonical)).toBe(`\n${raw.replace(/\n/g, "\n\n")}  \n`);
    expect(liteAssistantText(raw.replace("Mira:", "**Mira:**"), canonical)).toBe(raw);
  });
  it("previews complete lines only and nothing inside unfinished reasoning", () => {
    expect(previewText("One line.\nHalf a li")).toBe("One line.\n");
    expect(previewText("<think>planning\nmore\n")).toBe("");
    expect(previewText("<think>plan</think>\nStory line.\n")).toBe("<think>plan</think>\nStory line.\n");
  });
});

describe("director wardrobe", async () => {
  const { DEFAULT_NOVEL_CONFIG } = await import("../../../src/shared/types/novels.js");
  const { applyDirectorPlan, directorInstruction, directorLineInstruction } = await import("./liteDirector.js");
  const mira = { id: "m", name: "Mira", description: "", appearance: "short silver hair", personality: "", relationships: "", state: "", outfit: "dark green raincoat over a white sweater, black boots" };
  const memory = { summary: "", facts: [], threads: [], characters: [mira] };
  const scene = (id: string, lines: string[]) => ({ id, title: "", location: "Test pier", pov: "", lines: lines.map((text) => ({ speaker: "", text })), question: "", choices: [], illustrations: [], memory, createdAt: "", visuals: { location: "Test pier", setting: "pier", outfits: { m: mira.outfit } } });
  const story = (scenes: ReturnType<typeof scene>[]) => ({ id: "w", title: "", config: { ...DEFAULT_NOVEL_CONFIG, imagesEnabled: true, generationMode: "lite" as const }, cast: [], memory, scenes, turns: [], cursor: { scene: 0, line: 0 }, revision: 0, createdAt: "", updatedAt: "", cache: null });
  const needs = { choices: false, visuals: true };
  const plan = (at: string, clothes: string) => ({ question: "", choices: [], people: [], places: [], shots: [], outfits: [{ name: "Mira", clothes, at }] });
  it("shows the current clothes of people in the new text", () => {
    const s = story([scene("a", ["Mira shrugs off her raincoat in the warm hall."])]);
    expect(directorInstruction(s, needs, 1)).toContain("Current clothes: Mira: dark green raincoat over a white sweater, black boots.");
    expect(directorLineInstruction(s, needs, 1)).toContain("Current clothes: Mira: dark green raincoat");
    expect(directorInstruction(story([scene("b", ["Nobody named here, only the empty pier."])]), needs, 1)).not.toContain("Current clothes");
  });
  it("applies a complete new outfit, even when the quoted line is not found", () => {
    const s = story([scene("a", ["The synthetic hall is warm and very quiet tonight.", "Mira shrugs off her raincoat in the warm hall."])]);
    const changed = applyDirectorPlan(s, 1, plan("Mira shrugs off her", "white sweater, black boots"), needs);
    expect(changed.scenes[0].visuals?.outfits.m).toBe("white sweater, black boots");
    const guessed = applyDirectorPlan(s, 1, plan("a line that does not exist", "white sweater, black boots"), needs);
    expect(guessed.scenes[0].visuals?.outfits.m).toBe("white sweater, black boots");
  });
  it("keeps the earlier clothes for a picture before a mid-scene change", async () => {
    const { novelImagePrompt } = await import("./imagePrompt.js");
    const s = story([scene("a", ["Mira stands in the doorway, shaking off the rain.", "The lamps hum softly above the empty tables.", "Mira hangs her raincoat on a hook by the door."])]);
    const withShots = { ...plan("Mira hangs her raincoat", "white sweater, black boots"), shots: [{ at: "Mira stands in the doorway", who: ["Mira"], see: "Mira in the doorway." }, { at: "Mira hangs her raincoat", who: ["Mira"], see: "Mira hangs up her raincoat." }] };
    const applied = applyDirectorPlan(s, 1, withShots, needs);
    const [before, after] = applied.scenes[0].illustrations;
    expect(before.outfits).toEqual({ m: mira.outfit });
    expect(after.outfits).toBeUndefined();
    expect(novelImagePrompt(applied, applied.scenes[0], before)).toContain(`Mira is wearing ${mira.outfit}.`);
    expect(novelImagePrompt(applied, applied.scenes[0], after)).toContain("Mira is wearing white sweater, black boots.");
  });
});
